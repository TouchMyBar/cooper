// Dev-only generator (no dependencies, not shipped/imported at runtime).
// Renders three short 16-bit mono PCM WAVs and prints them as base64 data URLs
// to paste into src/sounds.ts BUILTIN. Run once: `node scripts/gen-sounds.mjs`.
// WAV/PCM is used because it decodes on every webview engine (incl. WebKitGTK).

const RATE = 44100;

function wav(samples) {
  const data = Buffer.alloc(samples.length * 2);
  for (let i = 0; i < samples.length; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    data.writeInt16LE((s < 0 ? s * 0x8000 : s * 0x7fff) | 0, i * 2);
  }
  const header = Buffer.alloc(44);
  header.write("RIFF", 0);
  header.writeUInt32LE(36 + data.length, 4);
  header.write("WAVE", 8);
  header.write("fmt ", 12);
  header.writeUInt32LE(16, 16); // PCM chunk size
  header.writeUInt16LE(1, 20); // PCM
  header.writeUInt16LE(1, 22); // mono
  header.writeUInt32LE(RATE, 24);
  header.writeUInt32LE(RATE * 2, 28); // byte rate
  header.writeUInt16LE(2, 32); // block align
  header.writeUInt16LE(16, 34); // bits
  header.write("data", 36);
  header.writeUInt32LE(data.length, 40);
  return Buffer.concat([header, data]);
}

const dataUrl = (buf) => "data:audio/wav;base64," + buf.toString("base64");

// A soft "pop": a short sine that rises slightly then decays fast.
function pop() {
  const dur = 0.09;
  const n = Math.floor(RATE * dur);
  const s = new Array(n);
  for (let i = 0; i < n; i++) {
    const t = i / RATE;
    const env = Math.exp(-t * 45);
    const f = 440 + 520 * Math.exp(-t * 30);
    s[i] = Math.sin(2 * Math.PI * f * t) * env * 0.6;
  }
  return s;
}

// A "click": a very short filtered impulse.
function click() {
  const dur = 0.03;
  const n = Math.floor(RATE * dur);
  const s = new Array(n);
  for (let i = 0; i < n; i++) {
    const t = i / RATE;
    const env = Math.exp(-t * 260);
    s[i] = Math.sin(2 * Math.PI * 1700 * t) * env * 0.5;
  }
  return s;
}

// A "morse" dot-dash at ~620 Hz.
function morse() {
  const f = 620;
  const gap = 0.05;
  const dot = 0.06;
  const dash = 0.16;
  const seq = [
    [dot, true],
    [gap, false],
    [dash, true],
  ];
  const s = [];
  for (const [dur, on] of seq) {
    const n = Math.floor(RATE * dur);
    for (let i = 0; i < n; i++) {
      const t = i / RATE;
      // small fade in/out to avoid clicks
      const fade = Math.min(1, t / 0.005, (dur - t) / 0.005);
      s.push(on ? Math.sin(2 * Math.PI * f * t) * 0.5 * Math.max(0, fade) : 0);
    }
  }
  return s;
}

const out = {
  pop: dataUrl(wav(pop())),
  click: dataUrl(wav(click())),
  morse: dataUrl(wav(morse())),
};

import { writeFileSync } from "node:fs";
let ts = "// AUTO-GENERATED by scripts/gen-sounds.mjs — do not edit by hand.\n";
ts += "// Built-in notification sounds as base64 WAV data URLs.\n";
ts += "export const BUILTIN: Record<string, string> = {\n";
for (const [k, v] of Object.entries(out)) ts += `  ${k}: ${JSON.stringify(v)},\n`;
ts += "};\n";
writeFileSync(new URL("../src/sounds-builtin.ts", import.meta.url), ts);
console.log("wrote src/sounds-builtin.ts with", Object.keys(out).length, "sounds");
